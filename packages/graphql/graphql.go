package main

import (
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"strings"

	"github.com/graphql-go/graphql"

	"github.com/prusa3d/prusa-connect/sdk/routesapi"
)

// The HTTP surface: one address, two methods.
//
// The operator mounts this module at /graphql, so the host takes that prefix
// off before the request arrives and the paths below are written against the
// mount. POST is what every GraphQL client sends. GET carries the query in the
// URL, which is what a link, a browser address bar and a cache can hold.
//
// The host has already decided who is calling and whether they may reach this
// module before any of this runs. Nothing here checks a permission, because
// the module holds no graph: the finer decision, whether this person may see
// this printer, is made by the core on each wire call the resolvers make.

// maxQueryBytes bounds the query text. The host already bounds the whole body
// at routesapi.MaxModuleBody, and this is the smaller bound on the part that
// is parsed and walked: a query is written by a person or generated by a
// client, and neither produces one this long.
const maxQueryBytes = 64 << 10

// errNoQuery reports a request carrying no query to run.
var errNoQuery = errors.New("the request carries no query")

// errQueryTooLong reports a query over maxQueryBytes.
var errQueryTooLong = errors.New("the query is longer than this module runs")

// request is the GraphQL request as every client writes it, over POST as a
// JSON body and over GET as query parameters.
type request struct {
	Query     string         `json:"query"`
	Variables map[string]any `json:"variables,omitempty"`
	Operation string         `json:"operationName,omitempty"`
}

// routes is the surface this module serves. Both methods answer at the mount
// itself, so an operator who mounted the module at /graphql has both at
// /graphql and nothing below it.
func routes(schema *graphql.Schema) http.Handler {
	mux := http.NewServeMux()

	mux.HandleFunc("POST /", func(w http.ResponseWriter, r *http.Request) {
		asked, err := requestFromBody(r.Body)
		if err != nil {
			refuseRequest(w, err)

			return
		}

		execute(w, r, schema, asked)
	})

	mux.HandleFunc("GET /", func(w http.ResponseWriter, r *http.Request) {
		asked, err := requestFromURL(r)
		if err != nil {
			refuseRequest(w, err)

			return
		}

		execute(w, r, schema, asked)
	})

	// Everything else is this module's own not found. A module mounted at a
	// root prefix owns every path under it, so a client that guessed
	// /graphql/v2 reads a refusal from here rather than the core's.
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		problem(w, http.StatusNotFound, "graphql/NOT_FOUND",
			"this module serves the mount itself",
			"the module saw the path "+r.URL.Path+", and it answers GET and POST at the mount")
	})

	return mux
}

// execute runs one query and writes the answer.
//
// The status is 200 for every query the schema could run, including one whose
// fields were refused: GraphQL puts a refusal in the errors list beside
// whatever data did resolve, and a client reads both. A request that never
// became a query, a write sent as a GET and a query over the bounds in
// limits.go are refused before it runs, each with a status of its own.
func execute(w http.ResponseWriter, r *http.Request, schema *graphql.Schema, asked request) {
	if document := parsed(asked.Query); document != nil {
		if r.Method != http.MethodPost && writesOverGet(document, asked.Operation) {
			w.Header().Set("Allow", http.MethodPost)
			problem(w, http.StatusMethodNotAllowed, "graphql/METHOD_NOT_ALLOWED",
				"a GraphQL write is sent as a POST", errWriteOverGet.Error())

			return
		}

		if err := bound(document); err != nil {
			refuseRequest(w, err)

			return
		}
	}

	// The principal is the host's answer about who is calling, taken off the
	// request the host handed over. It is never a header the caller wrote, and
	// it is what every wire call the resolvers make is authorized as.
	ctx := withPrincipal(r.Context(), routesapi.PrincipalOf(r))

	result := graphql.Do(graphql.Params{
		Schema:         *schema,
		RequestString:  asked.Query,
		VariableValues: asked.Variables,
		OperationName:  asked.Operation,
		Context:        ctx,
	})

	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusOK)

	_ = json.NewEncoder(w).Encode(result)
}

// requestFromBody reads a POST body.
func requestFromBody(body io.Reader) (request, error) {
	raw, err := io.ReadAll(body)
	if err != nil {
		return request{}, err
	}

	var asked request
	if err = json.Unmarshal(raw, &asked); err != nil {
		return request{}, errors.New("the body is not a GraphQL request object")
	}

	return asked, hold(asked)
}

// requestFromURL reads a GET query string. The variables ride as one JSON
// object in a parameter, which is what every client that offers GraphQL over
// GET writes.
func requestFromURL(r *http.Request) (request, error) {
	query := r.URL.Query()

	asked := request{
		Query:     query.Get("query"),
		Operation: query.Get("operationName"),
	}

	if written := query.Get("variables"); written != "" {
		if err := json.Unmarshal([]byte(written), &asked.Variables); err != nil {
			return request{}, errors.New("the variables parameter is not a JSON object")
		}
	}

	return asked, hold(asked)
}

// hold refuses a request that is not one this module can run.
func hold(asked request) error {
	switch {
	case strings.TrimSpace(asked.Query) == "":
		return errNoQuery
	case len(asked.Query) > maxQueryBytes:
		return errQueryTooLong
	}

	return nil
}

// refuseRequest answers a request that never became a query.
func refuseRequest(w http.ResponseWriter, err error) {
	code := "graphql/REQUEST_INVALID"

	switch {
	case errors.Is(err, errQueryTooLong):
		code = "graphql/QUERY_TOO_LONG"
	case errors.Is(err, errQueryTooComplex):
		code = "graphql/QUERY_TOO_COMPLEX"
	}

	problem(w, http.StatusBadRequest, code, "the request is not a GraphQL request", err.Error())
}

// problem writes one refusal as RFC 9457 names it, which is the shape every
// other address on this server answers a refusal in.
//
// The codes are this module's own, namespaced by its short name. They are
// outside the core's registry on purpose: the core's codes are what a fault
// from the fleet carries, and these name a request that never reached it.
func problem(w http.ResponseWriter, status int, code, title, detail string) {
	w.Header().Set("Content-Type", "application/problem+json")
	w.WriteHeader(status)

	_ = json.NewEncoder(w).Encode(map[string]any{
		"type":      "about:blank",
		"status":    status,
		"code":      code,
		"title":     title,
		"detail":    detail,
		"params":    map[string]any{},
		"retryable": false,
	})
}
