// The files PrusaSlicer 2.x adds to the 3MF core.
const (
	ps2Config        = "Metadata/Slic3r_PE.config"
	ps2ModelConfig   = "Metadata/Slic3r_PE_model.config"
	ps2WipeTower     = "Metadata/Prusa_Slicer_wipe_tower_information.xml"
	ps2CustomGCodes  = "Metadata/Prusa_Slicer_custom_gcode_per_print_z.xml"
	ps2LayerRanges   = "Metadata/Prusa_Slicer_layer_config_ranges.xml"
	ps2SettingsGroup = "config"
)

// The bed layout of PrusaSlicer 2.9. The beds stand on a grid whose spacing
// follows from the bed's size, and an instance belongs to the bed of its first
// model part that is on a bed; placement.go has the test. Nothing about beds
// is stored in the file. The numbers are those of src/libslic3r/MultipleBeds.cpp,
// the same in every release from 2.9.0 to 2.9.6.
const (
	ps2MaxBeds = 9
	// ps2GapLimit and ps2GapShare give the gap between two beds:
	// min(100, 0.3 * the bed's diagonal).
	ps2GapLimit = 100.0
	ps2GapShare = 0.3
	// ps2LegacyGap is the gap before 2.9.0, where the beds stood in one row
	// with a fifth of the bed's width between them.
	ps2LegacyGap = 0.2
	// ps2LegacyMaxBeds bounds the row a pre-2.9 project is searched along.
	ps2LegacyMaxBeds = 64
	// ps2MaxOwnerHops bounds the components followed from an instance to the
	// object that holds its mesh. PrusaSlicer writes one.
	ps2MaxOwnerHops = 8
)

// prusa2 reads PrusaSlicer 2.x projects.
type prusa2 struct {
	settings map[string]string
	header   string
	config   []ps2Object
	// changes are the layer changes by bed index.
	changes map[int][]LayerChange
	// ranges are the layer ranges by the object's position, from 1.
	ranges map[int][]layerRange
}

// ps2Object is one object of Slic3r_PE_model.config.
type ps2Object struct {
	id        int
	instances int
	name      string
	// index is the object's position in the file, counted from 1.
	index   int
	volumes []ps2Volume
	// settings are the object's own settings.
	settings map[string]string
}

type ps2Volume struct {
	first, last int
	name        string
	kind        PartType
	settings    map[string]string
}

func (*prusa2) name() Dialect { return DialectPrusaSlicer2 }

func (*prusa2) matches(p Producer, a *archive) bool {
	if p.Name == "PrusaSlicer" {
		return !versionAtLeast(p.Version, ps3Major, 0)
	}

	if strings.HasPrefix(p.Name, "Slic3r") {
		return true
	}

	return a.entry(ps2Config) != nil || a.entry(ps2ModelConfig) != nil
}

func (d *prusa2) prepare(rd *reading) error {
	if f := rd.a.entry(ps2Config); f != nil {
		data, err := readAll(rd.ctx, f, rd.limits.MaxMetadataBytes, "MaxMetadataBytes")
		if err != nil {
			return err
		}

		d.settings, d.header = parseConfig(data)
	}

	if f := rd.a.entry(ps2ModelConfig); f != nil {
		data, err := readAll(rd.ctx, f, rd.limits.MaxMetadataBytes, "MaxMetadataBytes")
		if err != nil {
			return err
		}

		objects, ok := parseModelConfig(data)
		if !ok {
			rd.issue(IssueSettingsUnreadable, ps2ModelConfig)
		}

		d.config = objects
	}

	if f := rd.a.entry(ps2CustomGCodes); f != nil {
		data, err := readAll(rd.ctx, f, rd.limits.MaxMetadataBytes, "MaxMetadataBytes")
		if err != nil {
			return err
		}

		changes, ok := ps2LayerChanges(data)
		if !ok {
			rd.issue(IssueSettingsUnreadable, ps2CustomGCodes)
		}

		d.changes = changes
	}

	ranges, err := readLayerRanges(rd, ps2LayerRanges)
	if err != nil {
		return err
	}

	d.ranges = ranges
	rd.rules = extruderRules{
		count:         len(splitList(d.settings["nozzle_diameter"], ',')),
		roles:         prusaRoles,
		setAll:        true,
		printSettings: textGetter(d.settings),
	}

	rd.ranges = map[int][]triRange{}

	for _, o := range d.config {
		for _, v := range o.volumes {
			rd.ranges[o.id] = append(rd.ranges[o.id], triRange{firstTri: v.first, lastTri: v.last})
		}
	}

	if rd.producer.Version == "" {
		rd.producer.Name, rd.producer.Version = generatorOf(d.header)
	}

	return nil
}

// parseConfig reads the "; key = value" lines of Slic3r_PE.config, and the
// "; generated by ..." line at the top.
func parseConfig(data []byte) (map[string]string, string) {
	out := map[string]string{}
	header := ""

	for line := range strings.SplitSeq(string(data), "\n") {
		line = strings.TrimSuffix(line, "\r")

		rest, ok := strings.CutPrefix(line, ";")
		if !ok {
			continue
		}

		rest = strings.TrimSpace(rest)

		if generated, isHeader := strings.CutPrefix(rest, "generated by "); isHeader && header == "" {
			header = generated

			continue
		}

		key, value, ok := strings.Cut(rest, " = ")
		if !ok {
			key, value, ok = strings.Cut(rest, "=")
		}

		if ok {
			out[strings.TrimSpace(key)] = strings.TrimSpace(value)
		}
	}

	return out, header
}

// generatorOf reads the name and version from a line such as "PrusaSlicer
// 2.9.6+MacOS-arm64 on 2026-10-26 at 22:51:04 UTC" or "Slic3r Prusa Edition
// 1.41.0 on ...".
func generatorOf(header string) (string, string) {
	fields := strings.Fields(header)
	for i, field := range fields {
		if field != "" && field[0] >= '0' && field[0] <= '9' {
			version, _, _ := strings.Cut(field, "+")

			return strings.Join(fields[:i], " "), version
		}
	}

	return "", ""
}

// parseModelConfig reads Slic3r_PE_model.config: the objects with their
// names, and their volumes as runs of triangles of the object's mesh.
func parseModelConfig(data []byte) ([]ps2Object, bool) {
	var doc struct {
		Objects []struct {
			ID        int       `xml:"id,attr"`
			Instances int       `xml:"instances_count,attr"`
			Metadata  []ps2Meta `xml:"metadata"`
			Volumes   []struct {
				First    int       `xml:"firstid,attr"`
				Last     int       `xml:"lastid,attr"`
				Metadata []ps2Meta `xml:"metadata"`
			} `xml:"volume"`
		} `xml:"object"`
	}

	if xml.NewDecoder(bytes.NewReader(data)).Decode(&doc) != nil {
		return nil, false
	}

	out := make([]ps2Object, 0, len(doc.Objects))

	for _, o := range doc.Objects {
		object := ps2Object{
			id: o.ID, instances: o.Instances, name: metaValue(o.Metadata, "name"),
			index: len(out) + 1, settings: metaMap(o.Metadata),
		}

		for _, v := range o.Volumes {
			kind := PartModel
			if metaValue(v.Metadata, "modifier") == "1" {
				kind = PartModifier
			}

			if t := metaValue(v.Metadata, "volume_type"); t != "" {
				kind = PartType(t)
			}

			object.volumes = append(object.volumes, ps2Volume{
				first: v.First, last: v.Last, name: metaValue(v.Metadata, "name"), kind: kind,
				settings: metaMap(v.Metadata),
			})
		}

		out = append(out, object)
	}

	return out, true
}

type ps2Meta struct {
	Key   string `xml:"key,attr"`
	Value string `xml:"value,attr"`
}

// metaMap makes a table of the entries.
func metaMap(entries []ps2Meta) map[string]string {
	out := make(map[string]string, len(entries))
	for _, m := range entries {
		out[m.Key] = m.Value
	}

	return out
}

func metaValue(entries []ps2Meta, key string) string {
	for _, m := range entries {
		if m.Key == key {
			return m.Value
		}
	}

	return ""
}

// objects groups the build items under the objects of Slic3r_PE_model.config.
// PrusaSlicer writes the first instance of an object as the object holding the
// mesh, and every other instance as an object with one component pointing at
// it, so an item belongs to the object its components lead to.
func (d *prusa2) objects(rd *reading) ([]objectSpec, error) {
	if len(d.config) == 0 {
		return groupByObject(rd, func(*resource, component) PartType { return PartModel })
	}

	root := rd.models.root
	index := map[int]int{}
	specs := make([]objectSpec, 0, len(d.config))

	for _, o := range d.config {
		res := root.resources[o.id]
		if res == nil || res.mesh == nil {
			rd.issue(IssueUnknownReference, ps2ModelConfig)

			continue
		}

		parts := ps2Parts(o, res.mesh)
		if err := rd.useMeshes(len(parts)); err != nil {
			return nil, err
		}

		index[o.id] = len(specs)
		specs = append(specs, objectSpec{
			name: o.name, resourceID: o.id, parts: parts, settings: textGetter(o.settings),
			ranges:  d.ranges[o.index],
			support: supportExtruders(prusaSupport, overlay(textGetter(o.settings), textGetter(d.settings))),
		})
	}

	var orphans []buildItem

	for _, item := range root.items {
		owner := ps2Owner(rd.models, item.ref)
		if o, ok := index[owner]; ok && item.ref.path == root.path {
			specs[o].items = append(specs[o].items, item)
		} else {
			orphans = append(orphans, item)
		}
	}

	kept := specs[:0]

	for _, spec := range specs {
		if len(spec.items) > 0 {
			kept = append(kept, spec)
		}
	}

	if len(orphans) == 0 {
		return kept, nil
	}

	// Items no object of the config claims are grouped as plain 3MF.
	saved := root.items
	root.items = orphans
	extra, err := groupByObject(rd, func(*resource, component) PartType { return PartModel })
	root.items = saved

	if err != nil {
		return nil, err
	}

	return append(kept, extra...), nil
}

// ps2Owner follows an item's object through single components to the object
// that holds the mesh.
func ps2Owner(m *models, key resKey) int {
	for range ps2MaxOwnerHops {
		res := m.resource(key)
		if res == nil {
			return -1
		}

		if res.mesh != nil || len(res.comps) != 1 {
			return res.key.id
		}

		key = res.comps[0].ref
	}

	return -1
}

// ps2Parts makes one part of every volume, as the run of vertices its
// triangles use.
func ps2Parts(o ps2Object, m *mesh) []partSpec {
	if len(o.volumes) == 0 || len(m.ranges) != len(o.volumes) {
		return []partSpec{
			{
				part:   Part{Name: o.name, Type: PartModel},
				pieces: []piece{{mesh: m, lo: 0, hi: -1, tlast: -1, tr: Identity}},
			},
		}
	}

	parts := make([]partSpec, 0, len(o.volumes))

	for i, v := range o.volumes {
		r := m.ranges[i]

		var pieces []piece
		if r.lo >= 0 {
			pieces = []piece{{mesh: m, lo: r.lo, hi: r.hi, tfirst: r.firstTri, tlast: r.lastTri, tr: Identity}}
		}

		parts = append(
			parts,
			partSpec{part: Part{Name: v.name, Type: v.kind}, pieces: pieces, settings: textGetter(v.settings)},
		)
	}

	return parts
}

// legacy reports whether PrusaSlicer 2.9.6 lays the project out again when it
// opens it: Plater::priv::load_files calls MultipleBeds::rearrange_after_load
// only when the Application of the model is PrusaSlicer-<version> with a
// version below 2.9.0-alpha1. A file from any other program, or without that
// entry, is read on the grid as it stands.
func (d *prusa2) legacy(p Producer) bool {
	version, ok := strings.CutPrefix(p.Application, "PrusaSlicer-")
	if !ok {
		return false
	}

	return semverLess(version, ps2GridVersion)
}

// ps2GridVersion is the first version that lays the beds out on a grid.
const ps2GridVersion = "2.9.0-alpha1"

func (d *prusa2) place(rd *reading, p *Project, specs []objectSpec) {
	setup := ps2Setup(d.settings)
	shape := setup.BedShape

	if len(shape) < minPolygon {
		(&generic{}).place(rd, p, specs)
		p.Setups[0] = d.finishBeds(mergeSetup(setup, p.Setups[0]))

		return
	}

	s := size(shape)
	bed := newPS2Bed(shape, setup.MaxPrintHeight)
	gap := min(ps2GapLimit, ps2GapShare*diagonal(s))
	j := &judge{work: shapeWork * rd.limits.MaxVertices}

	grid := func(i int) Point {
		x, y := gridCoords(i)

		return Point{X: float64(x) * (s.X + gap), Y: float64(y) * (s.Y + gap)}
	}
	row := func(i int) Point {
		return Point{X: float64(i) * (s.X + ps2LegacyGap*s.X)}
	}

	lifts := make([]float64, len(specs))
	for o := range specs {
		lifts[o] = ps2Lift(&specs[o])
	}

	offset, moved := grid, map[InstanceRef]Point(nil)
	if d.legacy(rd.producer) {
		offset, moved = ps2Rearrange(j, p, specs, lifts, &bed, grid, row)
	}

	highest := 0

	for o := range p.Objects {
		for i := range p.Objects[o].Instances {
			ref := InstanceRef{Object: o, Instance: i}
			shift := moved[ref]
			beds := func(b int) Point {
				g := grid(b)

				return Point{X: g.X - shift.X, Y: g.Y - shift.Y}
			}

			inst := &p.Objects[o].Instances[i]
			b, placement := j.ps2Instance(&specs[o].shapes[i], lifts[o], &bed, beds, ps2MaxBeds)
			inst.Placement = placement

			if b >= 0 {
				inst.Bed = &BedRef{Setup: 0, Bed: b}
				highest = max(highest, b)
			}
		}
	}

	for i := 0; i <= highest; i++ {
		setup.Beds = append(setup.Beds, Bed{Index: i, Offset: offset(i), Size: s})
	}

	for o, object := range p.Objects {
		for i, inst := range object.Instances {
			if inst.Bed != nil {
				setup.Beds[inst.Bed.Bed].Instances = append(
					setup.Beds[inst.Bed.Bed].Instances,
					InstanceRef{Object: o, Instance: i},
				)
			}
		}
	}

	p.Setups = []Setup{d.finishBeds(setup)}
}

// finishBeds gives every bed the print order of the settings and the layer
// changes the file holds for its index. Changes for a bed that holds no
// instance are left out, as the bed does not exist.
func (d *prusa2) finishBeds(setup Setup) Setup {
	sequential := strings.TrimSpace(d.settings["complete_objects"]) == "1"

	for b := range setup.Beds {
		bed := &setup.Beds[b]
		bed.Sequential = sequential

		if changes := d.changes[bed.Index]; len(changes) > 0 {
			bed.LayerChanges = slices.Clone(changes)
			sortChanges(bed.LayerChanges)
		}
	}

	return setup
}

// ps2Rearrange is MultipleBeds::rearrange_after_load of 2.9.6. When every
// instance is on a bed of the row and more than one bed is used, the beds are
// the row, and each instance is judged on the grid as if it had moved from its
// bed of the row to the bed of the same index on the grid: moved holds that
// move. Otherwise the grid stays and nothing moves.
func ps2Rearrange(
	j *judge, p *Project, specs []objectSpec, lifts []float64, bed *ps2Bed, grid, row func(int) Point,
) (func(int) Point, map[InstanceRef]Point) {
	beds, all, highest := ps2Assign(j, p, specs, lifts, bed, row, ps2LegacyMaxBeds)
	if !all || highest == 0 {
		return grid, nil
	}

	moved := map[InstanceRef]Point{}

	for ref, b := range beds {
		g, r := grid(b), row(b)
		moved[ref] = Point{X: g.X - r.X, Y: g.Y - r.Y}
	}

	return row, moved
}

// ps2Assign finds the bed of every instance on the beds offset lays out, and
// reports the beds, whether every instance found one, and the highest bed
// found.
func ps2Assign(
	j *judge, p *Project, specs []objectSpec, lifts []float64, bed *ps2Bed, offset func(int) Point, beds int,
) (map[InstanceRef]int, bool, int) {
	out := map[InstanceRef]int{}
	all, highest := true, 0

	for o := range p.Objects {
		for i := range p.Objects[o].Instances {
			b, _ := j.ps2Instance(&specs[o].shapes[i], lifts[o], bed, offset, beds)
			if b < 0 {
				all = false

				continue
			}

			out[InstanceRef{Object: o, Instance: i}] = b
			highest = max(highest, b)
		}
	}

	return out, all, highest
}

// gridCoords places bed index i on the grid PrusaSlicer 2.9 grows in square
// shells: 0 at (0,0), then (1,0), (0,1), (1,1), (2,0), (2,1), (0,2), (1,2),
// (2,2) and on.
func gridCoords(i int) (int, int) {
	if i <= 0 {
		return 0, 0
	}

	shell := 1
	for (shell+1)*(shell+1) < i+1 {
		shell++
	}

	at := i + 1 - shell*shell
	if at <= shell {
		return shell, at - 1
	}

	return at - shell - 1, shell
}

// ps2Setup reads the setup from the settings of Slic3r_PE.config.
func ps2Setup(settings map[string]string) Setup {
	out := Setup{
		PrinterModel:   settings["printer_model"],
		PrinterProfile: unquote(settings["printer_settings_id"]),
		PrintProfile:   unquote(settings["print_settings_id"]),
		BedShape:       parseBedShape(settings["bed_shape"]),
		MaxPrintHeight: parseNumber(settings["max_print_height"]),
		Technology:     settings["printer_technology"],
		GCodeFlavor:    settings["gcode_flavor"],
		LabelObjects:   settings["gcode_label_objects"],
	}

	for _, name := range splitList(settings["filament_settings_id"], ';') {
		out.MaterialProfiles = append(out.MaterialProfiles, unquote(name))
	}

	flows := splitList(settings["nozzle_high_flow"], ',')

	for i, field := range splitList(settings["nozzle_diameter"], ',') {
		nozzle := Nozzle{DiameterMM: parseNumber(field)}
		if i < len(flows) {
			flow := flows[i] == "1"
			nozzle.HighFlow = &flow
		}

		out.Nozzles = append(out.Nozzles, nozzle)
	}

	out.Nozzles = singleHotEnd(out.Nozzles, settings["single_extruder_multi_material"])

	if out.Technology != "SLA" {
		out.Filaments = filaments(
			len(splitList(settings["nozzle_diameter"], ',')),
			splitKeep(settings["extruder_colour"], ';'),
			splitKeep(settings["filament_colour"], ';'),
			splitKeep(settings["filament_type"], ';'),
		)
	}

	if value, ok := settings["binary_gcode"]; ok {
		binary := value == "1"
		out.BinaryGCode = &binary
	}

	for _, key := range []string{"compatible_printers_condition", "compatible_prints_condition"} {
		if value := unquote(settings[key]); value != "" {
			out.Conditions = append(out.Conditions, value)
		}
	}

	if len(settings) > 0 {
		out.Settings = []SettingsGroup{{Name: ps2SettingsGroup, Values: settings}}
	}

	return out
}

// singleHotEnd keeps only the first nozzle of a printer that feeds several
// filaments into one hot end, such as a printer with an MMU. PrusaSlicer
// stores one nozzle_diameter for every extruder it slices for, and an MMU
// is one extruder per filament: "The printer multiplexes filaments into a
// single hot end", single_extruder_multi_material in
// src/libslic3r/PrintConfig.cpp of 2.9.6.
func singleHotEnd(nozzles []Nozzle, flag string) []Nozzle {
	if strings.Trim(strings.TrimSpace(flag), `"`) == "1" && len(nozzles) > 1 {
		return nozzles[:1]
	}

	return nozzles
}

// mergeSetup keeps what the settings said and the beds placement made.
func mergeSetup(settings, placed Setup) Setup {
	settings.Beds = placed.Beds

	return settings
}

// parseBedShape reads "0x0,250x0,250x210,0x210".
func parseBedShape(value string) []Point {
	var out []Point

	for _, corner := range splitList(value, ',') {
		left, right, ok := strings.Cut(corner, "x")
		if !ok {
			return nil
		}

		x, errX := strconv.ParseFloat(strings.TrimSpace(left), 64)
		y, errY := strconv.ParseFloat(strings.TrimSpace(right), 64)

		if errX != nil || errY != nil || !finite(x) || !finite(y) {
			return nil
		}

		out = append(out, Point{X: x, Y: y})
	}

	return out
}

func parseNumber(value string) float64 {
	n, err := strconv.ParseFloat(strings.TrimSpace(value), 64)
	if err != nil || !finite(n) {
		return 0
	}

	return n
}

// splitList splits a list value at sep, leaving separators inside double
// quotes alone, and drops empty fields.
func splitList(value string, sep byte) []string {
	var (
		out    []string
		quoted bool
		start  int
	)

	for i := 0; i <= len(value); i++ {
		if i < len(value) {
			switch value[i] {
			case '"':
				quoted = !quoted

				continue
			case '\\':
				i++

				continue
			}

			if value[i] != sep || quoted {
				continue
			}
		}

		if field := strings.TrimSpace(value[start:min(i, len(value))]); field != "" {
			out = append(out, field)
		}

		start = i + 1
	}

	return out
}

// unquote removes the double quotes PrusaSlicer writes around a value that
// holds a separator, such as a profile name with a semicolon in it.
func unquote(value string) string {
	value = strings.TrimSpace(value)
	if len(value) >= 2 && value[0] == '"' && value[len(value)-1] == '"' {
		if s, err := strconv.Unquote(value); err == nil {
			return s
		}

		return value[1 : len(value)-1]
	}

	return value
}

func (*prusa2) thumbnail(string) (BedRef, bool) { return BedRef{}, false }

// rewrite makes the selected instances printable and the others not, and
// swaps the chosen bed with bed 0: the command line of PrusaSlicer 2.9 slices
// bed 0 only. The colour changes and the wipe tower of the two beds swap with
// them.
func (d *prusa2) rewrite(ctx context.Context, rw *rewriting) error {
	chosen := rw.sel.Bed.Bed
	setup := rw.project.Setups[0]

	var shift Point
	if chosen > 0 && chosen < len(setup.Beds) {
		shift = setup.Beds[chosen].Offset
	}

	// The added copies stand on the chosen bed, which moves onto bed 0.
	if rw.placed != nil && chosen > 0 {
		rw.placed.shift = Point{X: -shift.X, Y: -shift.Y}
	}

	if err := rw.clearPS2Scripts(ctx); err != nil {
		return err
	}

	err := rw.rewriteItems(ctx, func(item int, attrs *tagAttrs, selected bool) {
		attrs.set("printable", boolAttr(selected))

		bed := rw.bedOf(item)
		if chosen == 0 || bed < 0 {
			return
		}

		switch bed {
		case chosen:
			attrs.moveTransform(-shift.X, -shift.Y)
		case 0:
			attrs.moveTransform(shift.X, shift.Y)
		}
	})
	if err != nil || chosen == 0 {
		return err
	}

	for _, name := range []string{ps2WipeTower, ps2CustomGCodes} {
		if err = rw.swapBedIndex(ctx, name, chosen); err != nil {
			return err
		}
	}

	return nil
}
